"""Build everything: STEP model, both sheets (DXF + PDF + PNG), clash and stacking checks, comparison with the issued sheets.
    python run.py          (needs: pip install cadquery ezdxf matplotlib)
"""
import itertools
import sys

import cadquery as cq

from ga_sheet import assembly, build_ga
from parts_sheet import build_parts_sheet, cut_len
from rack_model import build, mass_kg

NAMES = {1: "Pallet foot", 2: "Corner stub", 3: "Telescopic post", 4: "Post cap", 5: "Locating pin", 6: "Side rail",
         7: "End bearer", 8: "Centre rail", 9: "Corner gusset", 10: "Retainer bolt"}
SHEET_KG = {1: 0.6, 2: 1.34, 3: 5.05, 4: 0.06, 5: 0.04, 6: 5.57, 7: 4.69, 8: 8.08, 9: 0.10}


def clashes(parts, min_mm3=5.0):
    solids = [(k, i, s.val()) for k, lst in parts.items() for i, s in enumerate(lst)]
    out = []
    for (k1, i1, a), (k2, i2, b) in itertools.combinations(solids, 2):
        A, B = a.BoundingBox(), b.BoundingBox()
        if A.xmax < B.xmin or B.xmax < A.xmin or A.ymax < B.ymin or B.ymax < A.ymin or A.zmax < B.zmin or B.zmax < A.zmin:
            continue
        v = a.intersect(b).Volume()
        if v > min_mm3:
            out.append((k1, i1, k2, i2, v))
    return out


def main():
    p, parts = build()
    asm = assembly(parts)
    cq.exporters.export(cq.Workplane(obj=asm), "umbrella_rack.step")
    total, stack3 = build_ga(p, parts, "umbrella_rack_sheet1_GA")
    build_parts_sheet(p, parts, "umbrella_rack_sheet2_PARTS")
    lines = ["# Model against the issued sheets (RI-RACK-001 Rev F)", "", "Generated by run.py from rack_model.py. Nothing here is typed in.", "",
             "## Mass per part (kg each)", "", "| Item | Part | Model | Sheet | Difference |", "|---|---|---|---|---|"]
    for k in range(1, 10):
        m = mass_kg(parts[k][0].val()); s = SHEET_KG[k]
        lines.append(f"| {k} | {NAMES[k]} | {m:.3f} | {s:.2f} | {(m - s) / s * 100:+.1f}% |")
    lines += ["", f"Rack total from the model: **{total:.2f} kg** (sheet: approx 58 kg).", ""]
    bb = asm.BoundingBox()
    lines += ["## Heights and sizes read from the model", "",
              f"- Top of cap: {bb.zmax - (p.pin_len - p.cap_t):.0f} (sheet: 1585 TOP OF CAP)",
              f"- Top of pin: {bb.zmax:.0f}",
              f"- Plan over stubs: {p.long_outer:.0f} x {p.wide_outer:.0f} (sheet: 2000 x 1700)",
              f"- Three racks stacked, top of cap: {stack3:.0f} mm = {stack3 / 1000:.1f} m (sheet text: approx 4.7 m)", ""]
    cl = clashes(parts)
    lines += ["## Clash check inside one rack (overlap volume over 5 mm3)", ""]
    lines += [f"- item {a} #{b} with item {c} #{d}: {v:.0f} mm3" for a, b, c, d, v in cl] or ["- none"]
    top_cap = bb.zmax - (p.pin_len - p.cap_t)
    up = [(k, s.val().translate(cq.Vector(0, 0, top_cap))) for k, lst in parts.items() for s in lst]
    low = [(k, s.val()) for k, lst in parts.items() for s in lst]
    st = []
    for (k1, a) in up:
        A = a.BoundingBox()
        for (k2, b) in low:
            B = b.BoundingBox()
            if A.zmax < B.zmin or B.zmax < A.zmin or A.xmax < B.xmin or B.xmax < A.xmin or A.ymax < B.ymin or B.ymax < A.ymin:
                continue
            v = a.intersect(b).Volume()
            if v > 5:
                st.append((k1, k2, v))
    lines += ["", "## Stacking check (second rack lowered onto the first, foot on cap)", ""]
    lines += [f"- upper item {a} with lower item {b}: {v:.0f} mm3" for a, b, v in st] or ["- no overlap: foot sits on the cap, pin in the foot hole"]
    lines += ["", "## Clearances the model shows", "",
              f"- Post 40x40x3 inside stub 50x50x4: {p.stub_sec[0] - 2 * p.stub_sec[1] - p.post_sec[0]:.0f} mm total gap across the flats (inner {p.stub_sec[0] - 2 * p.stub_sec[1]} against 40). Galvanising adds coating thickness, so check the post still slides (sheet note 4).",
              f"- Retainer bolt {p.bolt_d:.0f} dia in {p.post_hole:.0f} dia holes: {p.post_hole - p.bolt_d:.0f} mm clearance.",
              f"- Locating pin {p.pin_d:.0f} dia in {p.cap_hole} cap hole: {p.cap_hole - p.pin_d:.1f} mm (plug weld). In the foot floor hole {p.foot_hole:.0f}: {p.foot_hole - p.pin_d:.0f} mm.", "",
              "## Not reproduced / assumed", "",
              "- '1600 CLEAR' on the end view: nothing in the model gives 1600. Rack to rack, the clear height between the top of the lower rails and the underside of the upper rails is "
              f"{top_cap + p.rail_bottom - p.rail_top:.0f}.",
              "- Foot shape and thickness are not on the sheets: modelled as a 130x130 flange with a pot below, 2.5 mm sheet, so the mass is about 0.59 kg (sheet 0.6).",
              "- Gusset position: modelled in the inside corner of each stub, right angle snipped 15, top face flush with the rail undersides. Check against the real part.",
              "- Fork tines, boxes and the 1070 / 1200 / 3450 figures are use inputs, not geometry: they are parameters in rack_model.py.", ""]
    open("COMPARE.md", "w").write("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    sys.exit(main())
