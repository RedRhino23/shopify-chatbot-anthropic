"""Rubber expansion joint: build the model, STEP, the sheet (DXF/PDF/PNG) and the comparison with the issued drawing.
    python run_joint.py joint_job_XXXX.json     (a job file like joint_job.example.json; real job files stay out of git)
"""
import json
import sys

import cadquery as cq

from joint_model import JParams, build, fastener_mass, masses
from joint_sheet import build_joint_sheet


def total_for(**kw):
    p = JParams(**kw)
    p, parts = build(p)
    return masses(p, parts)["total"]


def solve_ring_id(target, lo=205.0, hi=300.0):
    for _ in range(30):
        mid = (lo + hi) / 2
        if total_for(ring_id=mid) > target:
            lo = mid
        else:
            hi = mid
    return (lo + hi) / 2


def main():
    job = json.load(open(sys.argv[1] if len(sys.argv) > 1 else "joint_job.example.json", encoding="utf-8"))
    p, parts = build()
    cq.exporters.export(cq.Workplane(obj=cq.Compound.makeCompound([s.val() for l in parts.values() for s in l])), "rubber_joint_DN200.step")
    m = build_joint_sheet(p, parts, job, "rubber_joint_DN200_GA")
    rid = solve_ring_id(p.drawing_weight_kg)
    rows = "\n".join(f"| {rid_:.0f} | {total_for(ring_id=rid_):.1f} |" for rid_ in (215, 230, 245, 260, 275))
    rubber_sens = "\n".join(f"| {d:.2f} | {total_for(rubber_density=d * 1e-6):.1f} |" for d in (1.1, 1.25, 1.4))
    lines = [
        "# Rubber expansion joint: model against the issued drawing", "",
        "Generated by run_joint.py from joint_model.py.", "",
        "## Taken from the drawing (inputs)", "",
        f"- Face to face {p.length:.0f}, bore DN{p.bore:.0f}, flange OD {p.flange_od:.0f}, PCD {p.pcd}, {p.holes} holes dia {p.hole_d}, backing bar {p.ring_t:.0f} thick, {p.n_fasteners} fasteners, 2 backing bars, 1 rubber joint.",
        "- Arch width 37 and cavity 17 mm were measured off the drawn section along the axis, where the drawing is to scale.", "",
        "## Not on the drawing, so assumed (change in `JParams`)", "",
        f"- Tube and arch wall {p.tube_wall:.0f}, arch height {p.arch_h:.0f} above the tube, rubber flange face {p.flange_face_t:.0f} (flange 20 = 8 rubber + 12 ring), backing ring ID {p.ring_id:.0f}, rubber density {p.rubber_density * 1e6:.2f} g/cm3, M{p.bolt_d:.0f} x {p.bolt_len:.0f} bolt with nut, holes straddling the centrelines (22.5 deg).",
        "- The drawing is N.T.S. and its radial sizes are compressed (the 343 OD and DN200 are drawn about 1.7 to 2 times too tall compared with the length), so arch height and wall cannot be read off it.", "",
        "## Weight", "",
        f"- Drawing: approx {p.drawing_weight_kg:.0f} kg. Model: rubber {m['rubber']:.2f} + 2 backing bars {m['rings']:.2f} + {p.n_fasteners} fasteners {m['fasteners']:.2f} = **{m['total']:.1f} kg** ({(m['total'] - p.drawing_weight_kg) / p.drawing_weight_kg * 100:+.0f}%).",
        f"- The backing ring inside diameter that gives exactly {p.drawing_weight_kg:.0f} kg (everything else as assumed): **about {rid:.0f} mm**.", "",
        "| Backing ring ID (mm) | Total (kg) |", "|---|---|", rows, "",
        "| Rubber density (g/cm3) | Total (kg) |", "|---|---|", rubber_sens, "",
        "Most of the weight is the two 316 backing bars (about half) and the fasteners (about a third), so the ring ID and bolt size matter much more than the rubber.", "",
        "## Not modelled", "",
        "- Displacement capability (12 lateral, 17 axial), temperature and pressure rating: these come from the rubber design, not geometry.",
        "- Fabric plies and rubber layers (the drawing hatches them as dashed lines). The model has one rubber body.",
        "- Mating flange and the full bolt stack: the fasteners are counted and weighed, not drawn, as on the issued drawing.", ""]
    open("COMPARE_JOINT.md", "w", encoding="utf-8").write("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    sys.exit(main())
