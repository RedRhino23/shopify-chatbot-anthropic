"""Metallic bellows: build the model, STEP, the sheet (DXF/PDF/PNG) and a note of what is assumed.
    python run_bellows.py [bellows_job.json]
"""
import json
import math
import sys

import cadquery as cq

from bellows_model import BParams, build, masses
from bellows_sheet import build_bellows_sheet


def main():
    job = json.load(open(sys.argv[1] if len(sys.argv) > 1 else "bellows_job.example.json", encoding="utf-8"))
    p, parts = build()
    cq.exporters.export(cq.Workplane(obj=cq.Compound.makeCompound([s.val() for l in parts.values() for s in l])), "bellows_DN200.step")
    m = build_bellows_sheet(p, parts, job, "bellows_DN200_GA")
    rows = []
    for n in (4, 6, 8, 10):
        q, pp = build(BParams(n_conv=n)); mm = masses(q, pp)
        rows.append(f"| {n} | {q.length:.0f} | {q.face_to_face:.0f} | {mm['bellows']:.1f} | {mm['total']:.1f} |")
    lines = ["# Metallic bellows (DN200 class 150): what is modelled and what is assumed", "",
             "Generated by run_bellows.py from bellows_model.py. This is a generic design built from the standard U-convolution construction,",
             "not from an AFJ drawing (AFJ's website refused this machine, so no AFJ photo or drawing was used).", "",
             "## Assumed (all in `BParams`)", "",
             f"- Bore {p.bore:.0f}, {p.n_conv} convolutions, pitch {p.pitch:.0f} (root and crown radius pitch/4 = {p.pitch / 4:.0f}), height {p.height:.0f}, {p.plies} plies x {p.ply_t} mm {p.bellows_mat}, end tangents {p.tangent:.0f}.",
             f"- Flanges ASME B16.5 class 150 NPS 8 ({p.flange_od:.0f} OD, {p.pcd} PCD, {p.holes} x dia {p.hole_d}), {p.flange_t:.0f} thick, {p.flange_mat}, bellows tangents welded to the flange faces.",
             f"- Internal liner {p.liner_t:.0f} mm, {p.liner_gap:.0f} mm radial clearance to the bellows root, stopping {p.liner_short:.0f} short of the far flange.", "",
             "## From the model", "",
             f"- Face to face {p.face_to_face:.0f}, bellows length {p.length:.0f}, crown OD about {2 * (p.bore / 2 + p.T + p.height):.0f}.",
             f"- Mass: bellows {m['bellows']:.2f} + 2 flanges {m['flanges']:.2f} + liner {m['liner']:.2f} = **{m['total']:.1f} kg**.",
             f"- Effective area at mean diameter {p.bore + p.height:.0f}: {math.pi / 4 * (p.bore + p.height) ** 2 / 100:.0f} cm2 (pressure thrust = pressure x this area).", "",
             "Change one parameter and everything follows (face to face, weight, dimensions, notes). Number of convolutions:", "",
             "| Convolutions | Bellows length | Face to face | Bellows kg | Total kg |", "|---|---|---|---|---|", *rows, "",
             "## Not modelled (needs the real design)", "",
             "- Axial, lateral and angular movement, spring rate and cycle life. These come from the EJMA calculation for the real convolution shape, not from geometry.",
             "- Design pressure and temperature, test pressure, rating of the bellows (the sheet leaves blanks for them).",
             "- Tie rods, hinges, gimbals, external cover, drain, weld details, and any end connection other than a flat plate flange.",
             "- The real convolution profile: toroidal, omega, or a different height-to-pitch ratio.", "",
             "## What would make this a proper test", "",
             "- One AFJ bellows drawing (or a clear photo of the product page): bore, pitch, height, plies and thickness, end connections, liner, rods.",
             "- Then regenerate that drawing and compare, as for the rack and the rubber joint.", ""]
    open("COMPARE_BELLOWS.md", "w", encoding="utf-8").write("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    sys.exit(main())
